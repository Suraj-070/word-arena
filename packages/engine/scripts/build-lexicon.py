#!/usr/bin/env python3
"""Build the shared ESDB lexicon used by Word Arena.

The checkout must be en-wl/wordlist release rel-2026.02.25, commit
7e99edab8e32f9f9ea2b15f249ca8d4d67237410, with scowl.db already built
(`./combine.py create-db scowl.db` in that checkout). This script does not
download anything and does not merge the five dialects into one legal set.

Usage:
  python3 packages/engine/scripts/build-lexicon.py /path/to/wordlist
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

RELEASE = "rel-2026.02.25"
COMMIT = "7e99edab8e32f9f9ea2b15f249ca8d4d67237410"
PRESETS = (
    ("D", 1),
    ("B", 2),
    ("Z", 4),
    ("A", 8),
    ("C", 16),
)
WORD = re.compile(r"^[a-z]{2,31}$")
ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "src" / "lexicon-data.ts"
NOTICE_PATH = ROOT / "dictionary" / "NOTICE.md"
NOTICE_MODULE = ROOT / "src" / "notice.ts"


def require_commit(scowl: Path) -> None:
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=scowl, text=True).strip()
    if revision != COMMIT:
        raise SystemExit(f"{scowl} is {revision}, not {COMMIT}")


def extract(scowl: Path, code: str) -> set[str]:
    command = [
        "./scowl",
        "word-list",
        "60",
        code,
        "1",
        "--deaccent",
        "--categories=",
        "--wo-poses=abbr",
        "--wo-usage-notes=offensive-1,offensive-2,vulgar-1",
        "--apostrophe",
        "false",
        "--dot",
        "false",
    ]
    completed = subprocess.run(command, cwd=scowl, check=True, capture_output=True, text=True)
    kept: set[str] = set()
    for line in completed.stdout.splitlines():
        word = line.strip().lower()
        if WORD.fullmatch(word):
            kept.add(word)
    return kept


def notice(scowl: Path) -> str:
    copyright_text = (scowl / "Copyright").read_text()
    atkinson, rest = copyright_text.split("===", 1)
    sections = rest.split("===")
    titze = ""
    wordnet = ""
    for section in sections:
        if section.startswith(" AU"):
            titze = section.split("\n", 1)[1].strip() + "\n"
        elif section.startswith(" WordNet"):
            wordnet = section.split("\n", 1)[1].strip() + "\n"
    if not titze or not wordnet:
        raise SystemExit("The Copyright file did not contain the Titze and WordNet sections.")
    return f"""# Word Arena dictionary notices

Generated word lists from the English Speller Database (ESDB, previously SCOWL), release {RELEASE}, commit `{COMMIT}`.

Each preset is size 60 and variant level 1. The ESDB tool was run with `--deaccent`, `--categories=` (special categories removed), `--wo-poses=abbr` (abbreviations removed), `--wo-usage-notes=offensive-1,offensive-2,vulgar-1`, `--apostrophe false`, and `--dot false`. Presets, kept as separate sets: Australian `D` (default), British `-ise` `B`, Oxford `-ize` `Z`, American `A`, and Canadian `C`. A word that is legal in more than one preset is stored once and marked for each of those presets. Lookup never treats the union as legal for every dialect.

This file does not clear the licensing review in the Phase 0 architecture, section 6.5. Oxford `-ize` (`Z`) and Canadian (`C`) are not licence-cleared. Do not describe this notice as that clearance.

The Atkinson notice is required on every copy. The Titze notice is required because preset `D` uses spelling code `D`. The WordNet 1.6 extract is included as a precaution. The ESDB copyright says that extract might apply when what is distributed is not a speller dictionary or a generated word list. This artifact is a generated word list. In this release, rows tagged `[ukacd]` are size 85 only. This extract is size 60, so the UKACD verbatim-document condition is not attached, and that document is not copied here.

## Atkinson

{atkinson.strip()}

## Titze

{titze.strip()}

## WordNet

{wordnet.strip()}
"""


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: build-lexicon.py /path/to/en-wl/wordlist")
    scowl = Path(sys.argv[1]).resolve()
    require_commit(scowl)
    masks: dict[str, int] = {}
    counts: dict[str, int] = {}
    for code, bit in PRESETS:
        words = extract(scowl, code)
        counts[code] = len(words)
        for word in words:
            masks[word] = masks.get(word, 0) | bit
    lines = [f"{word} {masks[word]}" for word in sorted(masks)]
    text = "\n".join(lines)
    digest = hashlib.sha256(text.encode()).hexdigest()
    shared = sum(1 for mask in masks.values() if mask == 31)
    DATA_PATH.write_text(
        "\n".join(
            [
                "/**",
                f" * Generated by packages/engine/scripts/build-lexicon.py from ESDB {RELEASE}.",
                f" * Commit {COMMIT}. Do not edit by hand.",
                " * Oxford -ize (Z) and Canadian (C) are not licence-cleared.",
                " * LEXICON_SHA256 is the SHA-256 of LEXICON_TEXT, UTF-8, with no extra newline.",
                " */",
                f'export const LEXICON_RELEASE = "{RELEASE}" as const;',
                f'export const LEXICON_COMMIT = "{COMMIT}" as const;',
                f'export const LEXICON_SHA256 = "{digest}" as const;',
                "export const LEXICON_COUNTS = {",
                f"  D: {counts['D']},",
                f"  B: {counts['B']},",
                f"  Z: {counts['Z']},",
                f"  A: {counts['A']},",
                f"  C: {counts['C']},",
                f"  unique: {len(masks)},",
                f"  shared: {shared},",
                "} as const;",
                f"export const LEXICON_TEXT = `{text}`;",
                "",
            ]
        )
    )
    NOTICE_PATH.parent.mkdir(parents=True, exist_ok=True)
    text = notice(scowl)
    NOTICE_PATH.write_text(text)
    escaped = text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    NOTICE_MODULE.write_text(
        "/** Generated by packages/engine/scripts/build-lexicon.py. Do not edit by hand. */\n"
        f"export const DICTIONARY_NOTICE = `{escaped}`;\n"
    )
    print(
        f"words {len(masks)} bytes {DATA_PATH.stat().st_size} sha256 {digest} "
        f"counts {counts} shared {shared}"
    )


if __name__ == "__main__":
    main()
